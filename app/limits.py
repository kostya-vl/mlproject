"""Лимиты сервиса: обоснование — в README.md, раздел «Пределы и защита»."""

# Тело запроса: 1 МБ. PII-спан короткий (email ≤254, телефон ≤20),
# 1000 спанов × ~100 символов ≈ 100 КБ; 1 МБ — 10× запас, но не «книга».
MAX_BODY_BYTES = 1 * 1024 * 1024

# Параллелизм: sklearn-инференс CPU-bound; 4 потока — типичное число vCPU
# в CI/небольшой VM. Больше — конкуренция за GIL, меньше — простой.
MAX_CONCURRENT_REQUESTS = 4

# Таймаут одного предсказания: 10 с. Базовая модель на 1000 спанах — <1 с;
# 10 с — потолок, после которого клиент получает 504, а поток освобождается.
REQUEST_TIMEOUT_SEC = 10.0
